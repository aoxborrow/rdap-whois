// Regenerate src/whois/generated/servers.ts from the src/whois/servers/ directory listing:
// the FILENAME is the single source of truth for a server's hostname — `whois.nic.as.ts`
// registers 'whois.nic.as'. Add a server by creating the file (export const config:
// FormatConfig) and running `npm run whois:generate:servers`; the lockstep unit test
// (test/whois/servers.test.ts) fails CI if the generated map is stale. Deterministic output
// (alphabetical), write-if-changed. Same output home as the TLD table.
import fs from 'fs';
import path from 'path';
import { GENERATED_DIR, PACKAGE_DIR } from '../lib/paths';

// the configs and the generated registry, under src/whois/
const configsDir = path.join(PACKAGE_DIR, 'src/whois/servers');
const outputFile = path.join(GENERATED_DIR, 'servers.ts');

// hostname → unique import identifier (`whois.sk-nic.sk` → whoisSkNicSk). Punycode hosts
// (`whois.nic.xn--p1acf`) split to an empty part on `--`; drop it.
function identifier(host: string): string {
  return host
    .split(/[.-]/)
    .filter(Boolean)
    .map((part, i) => (i ? part[0].toUpperCase() + part.slice(1) : part))
    .join('');
}

const hosts = fs
  .readdirSync(configsDir)
  .filter(f => /^(whois|www)\./.test(f) && f.endsWith('.ts'))
  .map(f => f.slice(0, -3))
  .sort();

const idents = hosts.map(identifier);
const collision = idents.find((id, i) => idents.indexOf(id) !== i);
if (collision) throw new Error(`import identifier collision: ${collision}`);

const out = `// Generated by scripts/whois/generate-servers.ts. Do not edit by hand: run
// \`npm run whois:generate:servers\`
//
// The FILENAME is the server map: every whois.<host>.ts / www.<host>.ts in
// src/whois/servers/ registers its config under that hostname. To add a server,
// create the file (export const config: FormatConfig) and re-run the generator; the lockstep
// test fails CI if this file is stale.
import type { FormatConfig } from '../formats';
${hosts.map((h, i) => `import { config as ${idents[i]} } from '../servers/${h}';`).join('\n')}

export const FORMAT_CONFIGS: Record<string, FormatConfig> = {
${hosts.map((h, i) => `  '${h}': ${idents[i]},`).join('\n')}
};
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
const current = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : '';
if (current === out) {
  console.log(`src/whois/generated/servers.ts unchanged (${hosts.length} servers)`);
} else {
  fs.writeFileSync(outputFile, out);
  console.log(`wrote src/whois/generated/servers.ts (${hosts.length} servers)`);
}
