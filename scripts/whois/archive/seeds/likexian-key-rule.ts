// loosen a key to likexian's normal form (alphanumerics + single spaces) so our normalizeKey
// output — which keeps hyphens/dots — still matches their punctuation-stripped keys.
export function likexianField(normalizedKey: string): string | null {
  const loose = normalizedKey.replace(/[^a-z0-9]+/g, ' ').trim();
  return LIKEXIAN_KEY_RULE[loose] ?? null;
}
