// writes src/record/generated/countries.ts, the country tables the record reads, from
// i18n-iso-countries' English names and its alpha-3 codes. The library ships the tables, not
// the dependency, which would bring every locale into a Node bundle.
//
// Run: `npm run countries:generate`
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const en = require('i18n-iso-countries/langs/en.json') as {
  countries: Record<string, string | string[]>;
};
const codes = require('i18n-iso-countries/codes.json') as [string, string, string][];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = path.join(root, 'src/record/generated/countries.ts');

const names = Object.fromEntries(
  Object.entries(en.countries).map(([code, name]) => [code, Array.isArray(name) ? name : [name]])
);
const alpha3 = Object.fromEntries(codes.map(([two, three]) => [three, two]));

writeFileSync(
  outputFile,
  `// generated by scripts/generate-countries.ts from i18n-iso-countries. Do not edit by hand:
// run \`npm run countries:generate\`

// every ISO 3166-1 alpha-2 code with its English names, the usual one first
export const COUNTRY_NAMES = ${JSON.stringify(names, null, 2)} as const;

// ISO 3166-1 alpha-3 codes to alpha-2
export const ALPHA3_TO_ALPHA2: Record<string, string> = ${JSON.stringify(alpha3, null, 2)};
`,
  'utf8'
);
console.log(`country tables generated at ${outputFile}`);
